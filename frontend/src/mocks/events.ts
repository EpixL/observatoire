import type { EventSource, VeilleEvent } from '../types';

/** Horloge figée de la maquette : tout est déterministe (captures d'écran, tests). */
export const NOW = '2026-10-29T14:30:00Z';

const h = (hoursAgo: number): string => new Date(Date.parse(NOW) - hoursAgo * 3_600_000).toISOString().replace('.000Z', 'Z');

function src(
  id: string,
  name: string,
  kind: EventSource['kind'],
  official: boolean,
  hoursAgo: number | null,
  excerpt: string,
  origin: string,
  original = true,
): EventSource {
  return {
    id,
    name,
    kind,
    official,
    published_at: hoursAgo === null ? null : h(hoursAgo),
    retrieved_at: h(hoursAgo === null ? 2 : Math.max(hoursAgo - 0.2, 0.1)),
    url: `https://exemple.invalid/${id}`,
    excerpt,
    origin_id: origin,
    is_original: original,
  };
}

type Claim = NonNullable<VeilleEvent['claims']>[number];
function cl(id: number, category: string, claim_type: Claim['claim_type'], role: Claim['role'], confirmation: Claim['confirmation'], certainty: Claim['certainty'], declarant: string, statement: string, needs_review = false): Claim {
  return { id, category, claim_type, role, negated: false, confirmation, declarant, certainty, needs_review, statement };
}

